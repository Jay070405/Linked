import {useEffect, useId, useRef, useState} from 'react';
import {useCaseLang} from '../../i18n';
import {BASE} from './media';
import SIM from './data/sim-hotspots.json';
import {controlPress} from './control-press.mjs';

export function ControlCard({id, controls}) {
  const {zh} = useCaseLang();
  const labelId = useId(), hintId = useId();
  const music = id === 'music';
  const interactive = id === 'park' || id === 'ask' || music;
  const squeeze = id === 'ask';
  const [pressed, setPressed] = useState(false);
  const latest = useRef(controls);
  latest.current = controls;
  const gesture = useRef(null), input = useRef(null), suppressClick = useRef(false), clickTimer = useRef(0);
  if (!gesture.current) gesture.current = controlPress({
    begin: () => { setPressed(true); if (squeeze) latest.current.press(); },
    tap: () => { if (squeeze) latest.current.press(); else latest.current.photo(); },
    hold: () => { if (!squeeze) latest.current.capture(); },
    release: () => { setPressed(false); if (squeeze) latest.current.lift(); },
  });
  const cancel = () => {
    input.current = null; gesture.current.cancel();
    clearTimeout(clickTimer.current);
    clickTimer.current = setTimeout(() => { suppressClick.current = false; }, 0);
  };
  useEffect(() => {
    window.addEventListener('blur', cancel);
    const hidden = () => { if (document.hidden) cancel(); };
    document.addEventListener('visibilitychange', hidden);
    return () => {
      window.removeEventListener('blur', cancel);
      document.removeEventListener('visibilitychange', hidden);
      gesture.current.cancel();
      clearTimeout(clickTimer.current);
    };
  }, []);
  const begin = source => {
    if (input.current !== null) return;
    input.current = source;
    clearTimeout(clickTimer.current);
    suppressClick.current = true;
    gesture.current.start();
  };
  const end = source => {
    if (input.current !== source) return;
    input.current = null;
    gesture.current.end();
    // Suppress the click generated by this press; allow later assistive-tech clicks.
    clickTimer.current = setTimeout(() => { suppressClick.current = false; }, 0);
  };
  const events = interactive ? {
    onPointerDown: e => {
      if (e.button !== 0 || !e.isPrimary) return;
      e.currentTarget.setPointerCapture(e.pointerId);
      begin(e.pointerId);
    },
    onPointerUp: e => end(e.pointerId),
    onPointerCancel: cancel,
    onLostPointerCapture: cancel,
    onBlur: cancel,
    onKeyDown: e => {
      if (e.key !== ' ' && e.key !== 'Enter') return;
      e.preventDefault();
      if (!e.repeat) begin(e.key);
    },
    onKeyUp: e => {
      if (e.key !== ' ' && e.key !== 'Enter') return;
      e.preventDefault(); end(e.key);
    },
    onClick: e => { if (e.detail === 0 && !suppressClick.current) { if (squeeze) controls.press(); else controls.photo(); } },
    onContextMenu: e => e.preventDefault(),
  } : {};

  const indicator = id === 'park' && controls.indicator;
  const name = indicator ? 'sim-front-indicator' : 'sim-3q';
  const view = SIM.views[name];
  const spot = indicator ? view.hotspots.indicator : squeeze || music ? view.hotspots.squeeze_zone
    : id === 'park' ? view.hotspots.capture_control : view.hotspots.mic_ports.find(p => p.visible);
  const mic = view.hotspots.mic_ports.find(p => p.visible);
  const title = squeeze ? (zh ? '捏住镜腿，或说“Hey Arden”' : "Squeeze and hold the temple, or say 'Hey Arden'")
    : music ? (zh ? '轻点镜腿，暂停或播放' : 'Tap the temple to pause or play')
    : id === 'park' ? (zh ? '拍摄键 · 右镜腿顶部' : 'Capture control · top of the right temple')
    : (zh ? '麦克风' : 'Microphones');
  const hint = squeeze ? (zh ? '右镜腿挤压区 / 麦克风' : 'Right temple squeeze zone / microphones')
    : music ? (zh ? '挤压区 · 右镜腿外侧' : 'Squeeze zone · outer right temple')
    : id === 'park' ? (zh ? '按一下拍照，长按录像' : 'Press once for a photo, hold to record')
    : id === 'walk' ? (zh ? '说“带我回家”' : "say 'Walk me home'") : (zh ? '说“翻译一下”' : "say 'Translate this'");
  const Tag = interactive && !squeeze ? 'button' : 'div';
  const status = id === 'park' ? controls.rec.state === 'rec' ? (zh ? '正在录像 · 按一下结束' : 'Recording · press to finish')
    : controls.rec.state === 'saved' ? (controls.rec.kind === 'photo' ? (zh ? '照片已保存' : 'Photo saved') : (zh ? '视频已保存' : 'Video saved')) : ''
    : squeeze ? controls.ask === 'listening' ? (zh ? '正在聆听' : 'Listening') : controls.ask === 'answer' ? (zh ? '回答已显示' : 'Answer in your lens') : ''
    : music ? controls.playing ? (zh ? '播放中' : 'Playing') : (zh ? '已暂停' : 'Paused') : '';
  return <Tag className="ar-control-card" data-pressed={pressed || undefined} data-squeeze={squeeze || undefined}
    data-indicator={indicator || undefined} data-reduced={controls.reduced || undefined} type={Tag === 'button' ? 'button' : undefined}
    role={squeeze ? 'group' : undefined}
    aria-pressed={Tag === 'button' ? music ? controls.playing : pressed || controls.rec.state === 'rec' : undefined}
    aria-labelledby={labelId} aria-describedby={hintId}
    {...(squeeze ? {onKeyDown: e => {
      if (e.key.toLowerCase() !== 'h') return;
      e.preventDefault();
      if (!e.repeat) { cancel(); controls.voice(); }
    }} : music ? {onClick: controls.toggleMusic} : events)}>
    <span className="ar-control-visual" aria-hidden={squeeze ? undefined : 'true'}>
      {/* Load both views together; each overlay shares its image's exact box. */}
      {['sim-3q', 'sim-front-indicator'].map(n => {
        const v = SIM.views[n];
        return <span key={n} className="ar-control-view" data-visible={name === n || undefined} style={{aspectRatio: `${v.width} / ${v.height}`}}>
          <picture><source media="(max-width: 760px)" srcSet={`${BASE}/controls/${n}-600.webp`}/>
            <img src={`${BASE}/controls/${n}-900.webp`} width={v.width} height={v.height} alt="" draggable="false"/></picture>
          {name === n ? <>
            <svg className="ar-control-leader" aria-hidden="true" viewBox="0 0 100 100" preserveAspectRatio="none"><path d={`M ${spot.x_pct} ${spot.y_pct} V 92 H 6 V 100`}/></svg>
            {squeeze ? <>
              <button type="button" className="ar-control-hotspot" data-control="squeeze" aria-pressed={pressed}
                aria-label={zh ? '捏住右镜腿提问' : 'Squeeze and hold the right temple to ask'} aria-keyshortcuts="Space Enter"
                style={{left: `${spot.x_pct}%`, top: `${spot.y_pct}%`}} {...events}>
                <span className="ar-control-ring"/>
                <span className="ar-control-finger is-left" aria-hidden="true">›</span><span className="ar-control-finger is-right" aria-hidden="true">‹</span>
              </button>
              <button type="button" className="ar-control-hotspot" data-control="voice" aria-keyshortcuts="H"
                aria-label={zh ? '说“Hey Arden”提问' : "Say 'Hey Arden' to ask"}
                style={{left: `${mic.x_pct}%`, top: `${mic.y_pct}%`}} onClick={controls.voice}>
                <span className="ar-control-ring"/>
              </button>
            </> : <span className="ar-control-hotspot" data-control={music ? 'music' : interactive ? 'capture' : 'microphones'}
              style={{left: `${spot.x_pct}%`, top: `${spot.y_pct}%`}}>
              <span className="ar-control-ring"/>
            </span>}
          </> : null}
        </span>;
      })}
    </span>
    <span className="ar-control-label" id={labelId}>{interactive ? title : `${title} · ${hint}`}</span>
    <span className="ar-control-hint" id={hintId}>{interactive ? hint : zh ? '如何开始' : 'How it started'}</span>
    {interactive ? <small className="ar-control-key">{squeeze ? (zh ? '长按空格 · 捏住镜腿 / H · 语音提问' : 'Hold Space · squeeze / H · voice')
      : music ? (zh ? '空格 / Enter · 暂停或播放' : 'Space / Enter · pause or play')
      : zh ? '空格 / Enter · 长按可持续操作' : 'Space / Enter · hold to keep pressing'}</small> : null}
    {interactive ? <span className="ar-control-status" role="status">{status || '\u00a0'}</span> : null}
  </Tag>;
}
