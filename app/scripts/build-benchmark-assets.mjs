// Copies what the Ready for agents page needs from the design-to-code benchmark (p2-benchmark), unchanged where it can:
//   public/proto/benchmark/<run>/index.html     the two generated pricing pages the "Try the finding" demo re-themes
//                                               (S2-L0-r1, from the raw file; S2-L0V-r1, the same file plus variables)
//   public/assets/product/ready-for-agents/runs/<run>.webp
//                                               a small thumbnail of every scored build's render (runs/<run>/render.png),
//                                               for the ablation chart's tooltips
//   public/assets/product/ready-for-agents/s1-reference.webp
//                                               the sign-in screen's Figma export (reference/S1-L2.png; L0 is identical)
//   src/product/v2/data/benchmark-runs.js       per build: screen, level, how much of the injected token change reached
//                                               its code, per token (results/results.json, the exploratory columns)
//
//   node scripts/build-benchmark-assets.mjs [path-to-p2-benchmark]
//
// The pages are copied byte for byte: they are the agents' own output, including their Google Fonts link for Inter.
// Uses sharp from the Ready for agents prototype; this repo gains no dependency.
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const work = path.join(app, '../../../视觉设计作品集');
const bench = path.resolve(process.argv[2] || process.env.P2_BENCHMARK || path.join(work, 'p2-benchmark'));
const sharp = createRequire(path.join(work, 'pd-prototype/package.json'))('sharp');
const assets = path.join(app, 'public/assets/product/ready-for-agents');
const log = [];

for (const run of ['S2-L0-r1', 'S2-L0V-r1']) {
  const to = path.join(app, 'public/proto/benchmark', run);
  await fs.mkdir(to, {recursive: true});
  await fs.copyFile(path.join(bench, 'runs', run, 'index.html'), path.join(to, 'index.html'));
  log.push(`page ${run}`);
}

// every scored build: thumbnail + the numbers the chart plots
const SCREENS = {S1: 'Sign-in', S2: 'Pricing', S3: 'Settings', S4: 'Product grid', S5: 'Dashboard', S6: 'Profile'};
const results = JSON.parse(await fs.readFile(path.join(bench, 'results/results.json'), 'utf8')).rows;
await fs.mkdir(path.join(assets, 'runs'), {recursive: true});
const rows = [];
for (const r of results) {
  const src = path.join(bench, 'runs', r.run, 'render.png');
  const meta = await sharp(src).metadata();
  const desktop = meta.width > 1000;
  // desktop screens: the whole 1440 x 960 frame; phone screens: the top 390 x 560
  const crop = desktop ? {left: 0, top: 0, width: meta.width, height: Math.min(meta.height, 960)} : {left: 0, top: 0, width: meta.width, height: Math.min(meta.height, 560)};
  const width = desktop ? 300 : 150;
  const info = await sharp(src).extract(crop).resize({width}).webp({quality: 72, effort: 6}).toFile(path.join(assets, 'runs', `${r.run}.webp`));
  const t = k => (r[`expl_theme_${k}`] == null ? null : Math.round(r[`expl_theme_${k}`] * 1000) / 1000);
  rows.push({id: r.run, screen: r.screen, name: SCREENS[r.screen], level: r.level, rep: r.rep,
    share: Math.round(r.expl_themePropagation * 1000) / 1000,
    tokens: {primary: t('primary'), text: t('text-primary'), background: t('background'), border: t('border')},
    w: info.width, h: info.height});
}
log.push(`${rows.length} build thumbnails`);
await fs.writeFile(path.join(app, 'src/product/v2/data/benchmark-runs.js'),
  `// Generated by scripts/build-benchmark-assets.mjs from p2-benchmark/results/results.json (${rows.length} scored builds).\n` +
  `// share: the exploratory theme-propagation measure, the mean over evaluated tokens of how much of each overridden color\n` +
  `// followed in the themed render (0 to 1). tokens: the same per token; null where the screen has too little of that color.\n` +
  `// w, h: the thumbnail in public/assets/product/ready-for-agents/runs/<id>.webp.\n` +
  `export const RUNS = ${JSON.stringify(rows, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[\{/, '[\n  {').replace(/\}\]$/, '},\n]')};\n`);

const ref = await sharp(path.join(bench, 'reference/S1-L2.png')).webp({quality: 86, effort: 6}).toFile(path.join(assets, 's1-reference.webp'));
log.push(`s1-reference ${ref.width}x${ref.height}`);

console.log(`Benchmark assets:\n  ${log.join('\n  ')}`);
